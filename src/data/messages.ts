// Helper: mensaje aleatorio sin repetir dos veces seguidas
const recentMessages: Record<string, number> = {};
export function getRandomMessage(arr: string[], key: string): string {
  if (!recentMessages[key]) recentMessages[key] = -1;
  let idx = Math.floor(Math.random() * arr.length);
  // Intentar evitar repetir el último
  let attempts = 0;
  while (idx === recentMessages[key] && attempts < 10) {
    idx = Math.floor(Math.random() * arr.length);
    attempts++;
  }
  recentMessages[key] = idx;
  return arr[idx];
}
